"""Tests for progressive-disclosure index generation."""
from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from pat_okf_agent.wiki.index import plan_indexes, write_indexes


def write(root: Path, rel: str, meta: str, body: str = "") -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"---\n{meta}---\n{body}", encoding="utf-8")
    return path


class IndexTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        write(self.root, "patents/Alpha.md",
              "type: Patent\ntitle: Alpha\ndescription: First patent\n")
        write(self.root, "patents/Beta.md",
              "type: Patent\ntitle: Beta\ndescription: Second patent\n")
        write(self.root, "patents/Gamma.md",
              "type: Patent\ntitle: Gamma\n")
        write(self.root, "workflows/Coat.md",
              "type: Workflow\ntitle: Coating workflow\n")
        write(self.root, "RootNote.md",
              "type: Note\ntitle: Root note\ndescription: Top level\n")

    def test_root_index_links_sections_with_counts(self):
        pages = plan_indexes(self.root, max_entries=10)
        root = pages["index.md"]
        self.assertIn("<!-- generated by okf index -->", root)
        self.assertIn("- [patents](patents/index.md) — 3 concepts", root)
        self.assertIn("- [workflows](workflows/index.md) — 1 concept", root)
        self.assertIn("[Root note](RootNote.md)", root)
        self.assertIn("## Sections", root)
        self.assertIn("## General", root)

    def test_section_index_is_paginated(self):
        pages = plan_indexes(self.root, max_entries=2)
        first = pages["patents/index.md"]
        self.assertIn("# patents", first)
        self.assertIn("[Alpha](Alpha.md)", first)
        self.assertIn("[Beta](Beta.md)", first)
        self.assertNotIn("[Gamma](Gamma.md)", first)
        self.assertIn("[More](index-2.md)", first)
        second = pages["patents/index-2.md"]
        self.assertIn("[Gamma](Gamma.md)", second)
        self.assertIn("[Previous](index.md)", second)

    def test_entries_are_sorted_and_descriptions_rendered(self):
        pages = plan_indexes(self.root, max_entries=10)
        section = pages["patents/index.md"]
        self.assertLess(section.index("[Alpha]"), section.index("[Beta]"))
        self.assertIn("First patent", section)

    def test_special_markdown_characters_in_titles_are_escaped(self):
        write(self.root, "notes/Brackets.md",
              "type: Note\ntitle: 'A [bracket] note'\n")
        pages = plan_indexes(self.root, max_entries=10)
        self.assertIn(r"[A \[bracket\] note](Brackets.md)",
                      pages["notes/index.md"])

    def test_long_descriptions_are_truncated_to_one_line(self):
        write(self.root, "notes/Long.md",
              "type: Note\ntitle: Long\n"
              f"description: {'word ' * 80}\n")
        pages = plan_indexes(self.root, max_entries=10)
        line = next(line for line in pages["notes/index.md"].splitlines()
                    if line.startswith("- [Long]"))
        self.assertLess(len(line), 220)

    def test_write_indexes_creates_files_and_is_idempotent(self):
        written = write_indexes(self.root, max_entries=2)
        self.assertIn("patents/index.md", written)
        self.assertIn("patents/index-2.md", written)
        self.assertTrue((self.root / "patents/index.md").exists())
        before = (self.root / "patents/index.md").read_text(encoding="utf-8")
        write_indexes(self.root, max_entries=2)
        after = (self.root / "patents/index.md").read_text(encoding="utf-8")
        self.assertEqual(before, after)

    def test_empty_wiki_has_a_root_index(self):
        with tempfile.TemporaryDirectory() as empty:
            pages = plan_indexes(Path(empty))
            self.assertIn("# Knowledge Index", pages["index.md"])
            self.assertIn("No concepts yet", pages["index.md"])


if __name__ == "__main__":
    unittest.main()
