"""Progressive-disclosure index generation for an OKF wiki.

The root ``index.md`` stays tiny: it links to one section index per top-level
directory. Section indexes list at most ``max_entries`` concepts and paginate
the rest into ``index-2.md``, ``index-3.md``, ... so an agent can stop reading
as soon as it has enough context.
"""
from __future__ import annotations

import os
import posixpath
import re
from collections import defaultdict
from pathlib import Path

from .model import Concept, iter_concepts

__all__ = ["plan_indexes", "stale_indexes", "write_indexes"]

MARKER = "<!-- generated by okf index -->"
_GENERATED_RE = re.compile(r"^index(?:-\d+)?\.md$")


def plan_indexes(root: str | Path, *, max_entries: int = 50) -> dict[str, str]:
    """Return ``{relative_path: content}`` for every index page."""
    if max_entries < 1:
        raise ValueError("max_entries must be >= 1")
    root = Path(root)
    concepts = iter_concepts(root)

    groups: dict[str, list[Concept]] = defaultdict(list)
    for concept in concepts:
        section = concept.rel.split("/", 1)[0] if "/" in concept.rel else ""
        groups[section].append(concept)
    for entries in groups.values():
        entries.sort(key=lambda c: (c.title.casefold(), c.rel))

    sections = sorted(section for section in groups if section)
    pages: dict[str, str] = {}

    for section in sections:
        pages.update(_section_pages(section, groups[section], max_entries))

    general = groups.get("", [])
    pages["index.md"] = _root_index(sections, groups, general, max_entries)
    if len(general) > max_entries:
        for offset, chunk in enumerate(
                _chunks(general, max_entries), start=1):
            if offset == 1:
                continue
            pages[f"index-{offset}.md"] = _continued_root(
                chunk, offset, has_next=offset * max_entries < len(general))
    return pages


def write_indexes(root: str | Path, *, max_entries: int = 50) -> list[str]:
    """Write all index pages atomically; return the relative paths written."""
    root = Path(root)
    pages = plan_indexes(root, max_entries=max_entries)
    for rel, content in pages.items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_name(target.name + ".tmp")
        try:
            tmp.write_text(content, encoding="utf-8")
            os.replace(tmp, target)
        finally:
            if tmp.exists():
                tmp.unlink()
    return sorted(pages)


def stale_indexes(root: str | Path, *, max_entries: int = 50) -> list[str]:
    """Return generated index pages that are missing or out of date."""
    root = Path(root)
    pages = plan_indexes(root, max_entries=max_entries)
    stale: list[str] = []
    for rel, content in pages.items():
        target = root / rel
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            stale.append(rel)
    for path in root.rglob("*.md"):
        rel = path.relative_to(root).as_posix()
        if rel in pages or not _GENERATED_RE.match(path.name):
            continue
        try:
            text = path.read_text(encoding="utf-8")[:200]
        except OSError:
            continue
        if MARKER in text:
            stale.append(rel)
    return sorted(set(stale))


def _section_pages(section: str, entries: list[Concept],
                   max_entries: int) -> dict[str, str]:
    pages: dict[str, str] = {}
    chunks = list(_chunks(entries, max_entries))
    for number, chunk in enumerate(chunks, start=1):
        rel = (f"{section}/index.md" if number == 1
               else f"{section}/index-{number}.md")
        lines = [f"# {section}", "", MARKER, ""]
        lines.extend(_entry_line(concept, section) for concept in chunk)
        if number < len(chunks):
            lines.extend(["", f"[More](index-{number + 1}.md)"])
        if number > 1:
            previous = "index.md" if number == 2 else f"index-{number - 1}.md"
            lines.extend(["", f"[Previous]({previous})"])
        pages[rel] = "\n".join(lines) + "\n"
    return pages


def _root_index(sections: list[str], groups: dict[str, list[Concept]],
                general: list[Concept], max_entries: int) -> str:
    lines = ["# Knowledge Index", "", MARKER, ""]
    if not sections and not general:
        lines.append("No concepts yet.")
        return "\n".join(lines) + "\n"

    if sections:
        lines.extend(["## Sections", ""])
        for section in sections:
            count = len(groups[section])
            label = "concept" if count == 1 else "concepts"
            lines.append(f"- [{section}]({section}/index.md) — {count} {label}")
        lines.append("")

    if general:
        lines.extend(["## General", ""])
        for concept in general[:max_entries]:
            lines.append(_entry_line(concept, ""))
        if len(general) > max_entries:
            lines.extend(["", "[More](index-2.md)"])
    return "\n".join(lines).rstrip() + "\n"


def _continued_root(entries: list[Concept], number: int,
                    *, has_next: bool) -> str:
    lines = [f"# Knowledge Index (continued {number})", "", MARKER, ""]
    lines.extend(_entry_line(concept, "") for concept in entries)
    if has_next:
        lines.extend(["", f"[More](index-{number + 1}.md)"])
    previous = "index.md" if number == 2 else f"index-{number - 1}.md"
    lines.extend(["", f"[Previous]({previous})"])
    return "\n".join(lines) + "\n"


def _entry_line(concept: Concept, section: str) -> str:
    target = posixpath.relpath(concept.rel, section) if section else concept.rel
    if any(char.isspace() for char in target):
        target = f"<{target}>"
    line = f"- [{_escape(concept.title)}]({target})"
    description = " ".join(concept.description.split())
    if description:
        line += f" — {_clip(description, 150)}"
    return line


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace("[", r"\[").replace("]", r"\]")


def _clip(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[: max(1, limit - 1)].rstrip() + "…"


def _chunks(items: list[Concept], size: int):
    for start in range(0, len(items), size):
        yield items[start:start + size]
